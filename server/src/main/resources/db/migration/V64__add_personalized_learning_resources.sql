CREATE TABLE `edu_resource_generation_task` (
    `id` BIGINT NOT NULL COMMENT '主键',
    `student_user_id` BIGINT NOT NULL COMMENT '学生用户ID',
    `course_id` BIGINT NOT NULL COMMENT '课程ID',
    `chapter_id` BIGINT NOT NULL COMMENT '章节ID',
    `knowledge_point_id` BIGINT NOT NULL COMMENT '知识点ID',
    `profile_version_no` INT NOT NULL DEFAULT 0 COMMENT '生成时画像版本',
    `profile_snapshot_json` LONGTEXT NOT NULL COMMENT '生成时使用的脱敏画像快照',
    `idempotency_key` VARCHAR(64) NOT NULL COMMENT '学生侧幂等键',
    `request_message` VARCHAR(500) DEFAULT NULL COMMENT '补充学习诉求',
    `status` VARCHAR(32) NOT NULL DEFAULT 'PENDING' COMMENT '状态: PENDING/RUNNING/SUCCEEDED/FAILED',
    `progress_percent` INT NOT NULL DEFAULT 0 COMMENT '任务进度百分比',
    `current_role_code` VARCHAR(32) DEFAULT NULL COMMENT '当前执行角色',
    `attempt_no` INT NOT NULL DEFAULT 1 COMMENT '执行次数',
    `model_name` VARCHAR(128) DEFAULT NULL COMMENT '实际模型名称',
    `failure_type` VARCHAR(64) DEFAULT NULL COMMENT '失败类型',
    `failure_message` VARCHAR(500) DEFAULT NULL COMMENT '失败原因',
    `total_duration_ms` BIGINT DEFAULT NULL COMMENT '总耗时毫秒',
    `started_at` DATETIME DEFAULT NULL,
    `finished_at` DATETIME DEFAULT NULL,
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_edu_resource_task_idempotency` (`student_user_id`, `idempotency_key`),
    KEY `idx_edu_resource_task_student` (`student_user_id`, `course_id`, `created_at`),
    KEY `idx_edu_resource_task_course` (`course_id`, `status`, `created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='个性化学习资源生成任务';

CREATE TABLE `edu_resource_generation_step` (
    `id` BIGINT NOT NULL COMMENT '主键',
    `task_id` BIGINT NOT NULL COMMENT '生成任务ID',
    `attempt_no` INT NOT NULL COMMENT '任务执行次数',
    `role_code` VARCHAR(32) NOT NULL COMMENT '智能体角色编码',
    `role_name` VARCHAR(64) NOT NULL COMMENT '智能体角色名称',
    `step_order` INT NOT NULL COMMENT '执行顺序',
    `status` VARCHAR(32) NOT NULL DEFAULT 'PENDING' COMMENT '状态: PENDING/RUNNING/SUCCEEDED/FAILED',
    `input_summary` VARCHAR(1000) DEFAULT NULL COMMENT '脱敏后的输入摘要',
    `output_summary` VARCHAR(2000) DEFAULT NULL COMMENT '输出摘要',
    `model_name` VARCHAR(128) DEFAULT NULL COMMENT '实际模型名称',
    `duration_ms` BIGINT DEFAULT NULL COMMENT '耗时毫秒',
    `failure_message` VARCHAR(500) DEFAULT NULL COMMENT '失败原因',
    `started_at` DATETIME DEFAULT NULL,
    `finished_at` DATETIME DEFAULT NULL,
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_edu_resource_step_role` (`task_id`, `attempt_no`, `role_code`),
    KEY `idx_edu_resource_step_task` (`task_id`, `attempt_no`, `step_order`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='个性化学习资源智能体执行步骤';

CREATE TABLE `edu_generated_resource` (
    `id` BIGINT NOT NULL COMMENT '主键',
    `task_id` BIGINT NOT NULL COMMENT '生成任务ID',
    `student_user_id` BIGINT NOT NULL COMMENT '资源所属学生ID',
    `course_id` BIGINT NOT NULL COMMENT '课程ID',
    `chapter_id` BIGINT NOT NULL COMMENT '章节ID',
    `knowledge_point_id` BIGINT NOT NULL COMMENT '知识点ID',
    `resource_type` VARCHAR(32) NOT NULL COMMENT '类型: EXPLANATION/MIND_MAP/EXERCISE/CODE_LAB/EXTENDED_READING',
    `title` VARCHAR(256) NOT NULL COMMENT '资源标题',
    `summary` VARCHAR(1000) NOT NULL COMMENT '资源摘要',
    `content` LONGTEXT NOT NULL COMMENT 'Markdown或Mermaid内容',
    `content_format` VARCHAR(32) NOT NULL COMMENT '格式: MARKDOWN/MERMAID',
    `validation_status` VARCHAR(32) NOT NULL COMMENT '校验状态: PASSED/NEEDS_REVIEW/REJECTED',
    `validation_reason` VARCHAR(1000) NOT NULL COMMENT '事实校验理由',
    `confidence` DECIMAL(5,4) NOT NULL COMMENT '事实校验置信度',
    `publication_status` VARCHAR(32) NOT NULL DEFAULT 'DRAFT' COMMENT '发布状态: DRAFT/PUBLISHED/WITHDRAWN/REJECTED',
    `review_note` VARCHAR(1000) DEFAULT NULL COMMENT '教师审核意见',
    `reviewed_by` BIGINT DEFAULT NULL COMMENT '审核教师ID',
    `reviewed_at` DATETIME DEFAULT NULL,
    `published_at` DATETIME DEFAULT NULL,
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_edu_generated_resource_type` (`task_id`, `resource_type`),
    KEY `idx_edu_generated_resource_student` (`student_user_id`, `course_id`, `publication_status`),
    KEY `idx_edu_generated_resource_course` (`course_id`, `knowledge_point_id`, `resource_type`, `publication_status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='个性化生成学习资源';

CREATE TABLE `edu_generated_resource_citation` (
    `id` BIGINT NOT NULL COMMENT '主键',
    `resource_id` BIGINT NOT NULL COMMENT '生成资源ID',
    `kb_document_id` BIGINT NOT NULL COMMENT '知识库文档ID',
    `kb_chunk_id` BIGINT NOT NULL COMMENT '知识库片段ID',
    `document_title` VARCHAR(256) NOT NULL COMMENT '来源文档标题',
    `excerpt` VARCHAR(2000) NOT NULL COMMENT '引用片段',
    `page_no` INT DEFAULT NULL COMMENT '页码',
    `relevance_score` DECIMAL(10,6) NOT NULL COMMENT '检索相关度',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_edu_resource_citation_chunk` (`resource_id`, `kb_chunk_id`),
    KEY `idx_edu_resource_citation_resource` (`resource_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='生成学习资源引用';
